require('../helpers/setupS3Env');
const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const {hasMongo} = require('../helpers/testServer');
const {setupS3,submitVideo} = require('../helpers/s3Setup');
const {Response,Submission} = require('../../models');
const {alignStoredRetention} = require('../../services/retentionPolicy');
const {runRetentionCleanup} = require('../../services/retentionService');
const {getS3Service} = require('../../services/s3Service');
const DAY = 86400000;

test('legacy retention alignment corrects stored dates once, protects access and expires only due videos',{skip:!hasMongo},async t=>{
  const ctx=await setupS3(t);
  const now=new Date();
  const old=await submitVideo(ctx),recent=await submitVideo(ctx),current=await submitVideo(ctx);
  const currentBefore=await Response.findById(current.responseId);
  assert.equal(currentBefore.retentionDays,60);
  assert.ok(Math.abs(currentBefore.deleteAt-currentBefore.submittedAt-60*DAY)<60000);
  const oldStart=new Date(+now-70*DAY),recentStart=new Date(+now-40*DAY);
  await Response.updateOne({_id:old.responseId},{$set:{submittedAt:oldStart,deleteAt:new Date(+oldStart+180*DAY)},$unset:{retentionDays:1}});
  await Response.updateOne({_id:recent.responseId},{$set:{submittedAt:new Date(+recentStart-20*DAY),deleteAt:new Date(+recentStart+180*DAY)},$unset:{retentionDays:1}});
  const missing=await Response.create({requestId:ctx.requestId,status:'submitted',submittedAt:recentStart,clientName:'Legacy no deadline'});
  const batchId=crypto.randomUUID();
  await Response.updateMany({_id:{$in:[old.responseId,recent.responseId]}},{$set:{batchId}});
  await Submission.create({requestId:ctx.requestId,batchId,tokenHash:'a'.repeat(64),responseIds:[old.responseId,recent.responseId]});
  for(const action of ['play','download'])assert.equal((await ctx.client.get('/api/responses/'+old.responseId+'/'+action)).status,410);
  assert.equal((await ctx.client.get('/api/requests/'+ctx.requestId+'/submissions/'+batchId+'/download')).status,410);
  const rows=(await ctx.client.get('/api/requests/'+ctx.requestId+'/responses')).json.responses;
  const row=rows.find(r=>r.id===old.responseId);assert.equal(row.effectiveStatus,'expired');assert.equal(+new Date(row.deleteAt),+oldStart+60*DAY);
  const aligned=await alignStoredRetention();assert.equal(aligned,3);
  assert.equal(await alignStoredRetention(),0,'alignment must not subtract 120 days twice');
  assert.equal(+(await Response.findById(old.responseId)).deleteAt,+oldStart+60*DAY);
  assert.equal(+(await Response.findById(recent.responseId)).deleteAt,+recentStart+60*DAY,'preserve storage clock after migration');
  assert.equal(+(await Response.findById(missing.id)).deleteAt,+recentStart+60*DAY);
  assert.equal(+(await Response.findById(current.responseId)).deleteAt,+currentBefore.deleteAt,'new records do not move');
  const expired=await runRetentionCleanup({s3:getS3Service(),now});assert.ok(expired.expired>=1);
  const after=await Response.findById(old.responseId).select('+videoKey');assert.equal(after.status,'expired');assert.equal(after.videoKey,undefined);assert.equal(after.clientName,'Carla Client');
  assert.equal((await Response.findById(recent.responseId)).status,'submitted');assert.equal((await Response.findById(current.responseId)).status,'submitted');
  assert.equal(await Response.countDocuments({_id:old.responseId}),1);
  assert.equal((await runRetentionCleanup({s3:getS3Service(),now})).expired,0);
});
